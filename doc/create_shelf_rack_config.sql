-- =============================================
-- 智能货架配置表 - 存储每个料架(RACK)绑定的货架服务IP地址
-- =============================================

CREATE TABLE SHELF_RACK_CONFIG (
    CONFIG_ID       VARCHAR2(50)  NOT NULL,
    RACK_CODE       VARCHAR2(50)  NOT NULL,
    SHELF_IP        VARCHAR2(100) NOT NULL,
    SHELF_PORT      NUMBER        DEFAULT 9090,
    STATUS          VARCHAR2(10)  DEFAULT 'ACTIVE',
    REMARK          VARCHAR2(200),
    CREATE_TIME     DATE          DEFAULT SYSDATE,
    UPDATE_TIME     DATE          DEFAULT SYSDATE,
    CONSTRAINT PK_SHELF_RACK_CONFIG PRIMARY KEY (CONFIG_ID),
    CONSTRAINT UK_SHELF_RACK_CODE UNIQUE (RACK_CODE)
);

COMMENT ON TABLE SHELF_RACK_CONFIG IS '智能货架配置表 - 料架与货架服务IP绑定关系';
COMMENT ON COLUMN SHELF_RACK_CONFIG.CONFIG_ID IS '主键ID (UUID)';
COMMENT ON COLUMN SHELF_RACK_CONFIG.RACK_CODE IS '料架编号 (对应V_LOCATION_ALL.RACK)';
COMMENT ON COLUMN SHELF_RACK_CONFIG.SHELF_IP IS '货架服务IP地址 (如 192.168.1.10)';
COMMENT ON COLUMN SHELF_RACK_CONFIG.SHELF_PORT IS '货架服务端口 (默认9090)';
COMMENT ON COLUMN SHELF_RACK_CONFIG.STATUS IS '状态: ACTIVE=启用, INACTIVE=停用';
COMMENT ON COLUMN SHELF_RACK_CONFIG.REMARK IS '备注';
COMMENT ON COLUMN SHELF_RACK_CONFIG.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN SHELF_RACK_CONFIG.UPDATE_TIME IS '更新时间';

