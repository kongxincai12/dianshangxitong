CREATE TABLE PDA_EQP_STATION_REL (
    ID NUMBER PRIMARY KEY,
    EQP_CODE VARCHAR2(100) NOT NULL,
    STATION_ID VARCHAR2(100) NOT NULL,
    STATUS VARCHAR2(10) DEFAULT 'Y' NOT NULL,
    REMARK VARCHAR2(500),
    OPERATE_USER VARCHAR2(100),
    OPERATE_TIME DATE DEFAULT SYSDATE
);

CREATE SEQUENCE SEQ_PDA_EQP_STATION_REL START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE UNIQUE INDEX UK_PDA_EQP_STATION_REL ON PDA_EQP_STATION_REL (EQP_CODE, STATION_ID);
CREATE INDEX IDX_PDA_EQP_STATION_EQP ON PDA_EQP_STATION_REL (EQP_CODE);
CREATE INDEX IDX_PDA_EQP_STATION_STATION ON PDA_EQP_STATION_REL (STATION_ID);
