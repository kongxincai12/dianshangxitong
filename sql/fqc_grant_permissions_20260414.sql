-- ============================================================
-- FQC 人员权限开通脚本（按名单批量授权）
-- 日期: 2026-04-14
-- 说明:
--   1) 工号即 USER_ID
--   2) 角色为 FQC_INSPECTOR
--   3) 站点标识 SITE='FQC'
--   4) 脚本可重复执行（MERGE 幂等）
-- ============================================================

-- 1. 确保 FQC 角色存在
MERGE INTO MES_INSP_ROLES r
USING (
    SELECT 'FQC_INSPECTOR' AS ROLE_CODE, 'FQC检验员' AS ROLE_NAME, 1 AS ROLE_LEVEL FROM DUAL
) src
ON (r.ROLE_CODE = src.ROLE_CODE)
WHEN NOT MATCHED THEN
    INSERT (ID, ROLE_CODE, ROLE_NAME, ROLE_LEVEL)
    VALUES (SYS_GUID(), src.ROLE_CODE, src.ROLE_NAME, src.ROLE_LEVEL);

-- 2. 同步人员到 MES_INSP_USERS（若已存在则更新姓名并激活）
MERGE INTO MES_INSP_USERS u
USING (
    SELECT '10060808' AS EMPLOYEE_ID, '曾丽红' AS EMPLOYEE_NAME FROM DUAL UNION ALL
    SELECT '16011503', '陈书芝' FROM DUAL UNION ALL
    SELECT '14021320', '邱小君' FROM DUAL UNION ALL
    SELECT '23110601', '谢玉连' FROM DUAL UNION ALL
    SELECT '14021104', '李晶妹' FROM DUAL UNION ALL
    SELECT '15012303', '赵宁' FROM DUAL UNION ALL
    SELECT '13082709', '关海萍' FROM DUAL UNION ALL
    SELECT '21031210', '李艳玲' FROM DUAL UNION ALL
    SELECT '23100801', '李玲玲' FROM DUAL UNION ALL
    SELECT '25030303', '胡广芬' FROM DUAL UNION ALL
    SELECT '25041004', '戴炎洁' FROM DUAL UNION ALL
    SELECT '25041603', '沈淑青' FROM DUAL UNION ALL
    SELECT '25061901', '陈乐' FROM DUAL UNION ALL
    SELECT '26022607', '杨应王' FROM DUAL UNION ALL
    SELECT '26022701', '杨小芳' FROM DUAL UNION ALL
    SELECT '17080213', '秦明艳' FROM DUAL UNION ALL
    SELECT '16032801', '朱红山' FROM DUAL UNION ALL
    SELECT '26031604', '张海玲' FROM DUAL UNION ALL
    SELECT '26031807', '唐玲英' FROM DUAL UNION ALL
    SELECT '26040902', '徐鲜鲜' FROM DUAL
) src
ON (u.EMPLOYEE_ID = src.EMPLOYEE_ID)
WHEN MATCHED THEN
    UPDATE SET u.EMPLOYEE_NAME = src.EMPLOYEE_NAME,
               u.IS_ACTIVE = '1'
WHEN NOT MATCHED THEN
    INSERT (ID, EMPLOYEE_ID, EMPLOYEE_NAME, IS_ACTIVE)
    VALUES (SYS_GUID(), src.EMPLOYEE_ID, src.EMPLOYEE_NAME, '1');

-- 3. 授权 FQC_INSPECTOR 到 MES_INSP_USER_PERMISSIONS
MERGE INTO MES_INSP_USER_PERMISSIONS p
USING (
    SELECT
        u.EMPLOYEE_ID AS USER_ID,
        r.ID AS ROLE_ID
    FROM MES_INSP_USERS u
    JOIN MES_INSP_ROLES r ON r.ROLE_CODE = 'FQC_INSPECTOR'
    WHERE u.EMPLOYEE_ID IN (
        '10060808','16011503','14021320','23110601','14021104',
        '15012303','13082709','21031210','23100801','25030303',
        '25041004','25041603','25061901','26022607','26022701',
        '17080213','16032801','26031604','26031807','26040902'
    )
) src
ON (p.USER_ID = src.USER_ID AND p.ROLE_ID = src.ROLE_ID)
WHEN MATCHED THEN
    UPDATE SET p.SITE = 'FQC',
               p.IS_ACTIVE = 1
WHEN NOT MATCHED THEN
    INSERT (ID, USER_ID, ROLE_ID, SITE, IS_ACTIVE)
    VALUES (SYS_GUID(), src.USER_ID, src.ROLE_ID, 'FQC', 1);

COMMIT;

-- 4. 校验结果
SELECT p.USER_ID,
       u.EMPLOYEE_NAME,
       r.ROLE_CODE,
       p.SITE,
       p.IS_ACTIVE
  FROM MES_INSP_USER_PERMISSIONS p
  JOIN MES_INSP_ROLES r ON r.ID = p.ROLE_ID
  LEFT JOIN MES_INSP_USERS u ON u.EMPLOYEE_ID = p.USER_ID
 WHERE r.ROLE_CODE = 'FQC_INSPECTOR'
   AND p.USER_ID IN (
       '10060808','16011503','14021320','23110601','14021104',
       '15012303','13082709','21031210','23100801','25030303',
       '25041004','25041603','25061901','26022607','26022701',
       '17080213','16032801','26031604','26031807','26040902'
   )
 ORDER BY p.USER_ID;
