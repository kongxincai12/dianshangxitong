-- ============================================
-- 简易电商系统 (shop 模块) 建表脚本 - Oracle
-- 包含: 分类 / 商品 / 购物车 / 订单主表 / 订单明细
-- ============================================

-- 商品分类表
CREATE TABLE SHOP_CATEGORY (
    ID           VARCHAR2(32)  PRIMARY KEY,
    NAME         VARCHAR2(100) NOT NULL,
    SORT_NO      NUMBER        DEFAULT 0,
    CREATE_TIME  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE  SHOP_CATEGORY IS '商品分类表';
COMMENT ON COLUMN SHOP_CATEGORY.ID IS '主键ID(UUID)';
COMMENT ON COLUMN SHOP_CATEGORY.NAME IS '分类名称';
COMMENT ON COLUMN SHOP_CATEGORY.SORT_NO IS '排序号(升序)';

-- 商品表
CREATE TABLE SHOP_PRODUCT (
    ID           VARCHAR2(32)   PRIMARY KEY,
    NAME         VARCHAR2(200)  NOT NULL,
    CATEGORY_ID  VARCHAR2(32),
    PRICE        NUMBER(12,2)   DEFAULT 0 NOT NULL,
    STOCK        NUMBER         DEFAULT 0 NOT NULL,
    DESCRIPTION  VARCHAR2(2000),
    IMAGE_URL    VARCHAR2(500),
    STATUS       NUMBER(1)      DEFAULT 1 NOT NULL,
    CREATE_TIME  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_TIME  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IDX_SHOP_PRODUCT_CATEGORY ON SHOP_PRODUCT(CATEGORY_ID);
CREATE INDEX IDX_SHOP_PRODUCT_NAME     ON SHOP_PRODUCT(NAME);
COMMENT ON TABLE  SHOP_CATEGORY IS '商品分类表';
COMMENT ON TABLE  SHOP_PRODUCT IS '商品表';
COMMENT ON COLUMN SHOP_PRODUCT.PRICE IS '销售单价(元)';
COMMENT ON COLUMN SHOP_PRODUCT.STOCK IS '库存数量';
COMMENT ON COLUMN SHOP_PRODUCT.STATUS IS '状态: 1-上架, 0-下架';

-- 购物车表
CREATE TABLE SHOP_CART (
    ID           VARCHAR2(32)  PRIMARY KEY,
    USER_ID      VARCHAR2(100) NOT NULL,
    PRODUCT_ID   VARCHAR2(32)  NOT NULL,
    QUANTITY     NUMBER        DEFAULT 1 NOT NULL,
    CREATE_TIME  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_TIME  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX UK_SHOP_CART_USER_PRODUCT ON SHOP_CART(USER_ID, PRODUCT_ID);
COMMENT ON TABLE  SHOP_CART IS '购物车表';
COMMENT ON COLUMN SHOP_CART.USER_ID IS '用户(工号)ID';

-- 订单主表
CREATE TABLE SHOP_ORDER (
    ID               VARCHAR2(32)  PRIMARY KEY,
    ORDER_NO         VARCHAR2(32)  NOT NULL,
    USER_ID          VARCHAR2(100) NOT NULL,
    TOTAL_AMOUNT     NUMBER(12,2)  DEFAULT 0 NOT NULL,
    STATUS           VARCHAR2(20)  DEFAULT 'PENDING' NOT NULL,
    RECEIVER_NAME    VARCHAR2(100),
    RECEIVER_PHONE   VARCHAR2(50),
    RECEIVER_ADDRESS VARCHAR2(500),
    REMARK           VARCHAR2(500),
    PAY_TIME         TIMESTAMP,
    CREATE_TIME      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_TIME      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX UK_SHOP_ORDER_NO ON SHOP_ORDER(ORDER_NO);
CREATE INDEX IDX_SHOP_ORDER_USER ON SHOP_ORDER(USER_ID);
CREATE INDEX IDX_SHOP_ORDER_STATUS ON SHOP_ORDER(STATUS);
COMMENT ON TABLE  SHOP_ORDER IS '电商订单主表';
COMMENT ON COLUMN SHOP_ORDER.STATUS IS '订单状态: PENDING-待支付, PAID-已支付, CANCELLED-已取消';

-- 订单明细表
CREATE TABLE SHOP_ORDER_ITEM (
    ID            VARCHAR2(32)  PRIMARY KEY,
    ORDER_ID      VARCHAR2(32)  NOT NULL,
    PRODUCT_ID    VARCHAR2(32)  NOT NULL,
    PRODUCT_NAME  VARCHAR2(200),
    PRICE         NUMBER(12,2)  DEFAULT 0 NOT NULL,
    QUANTITY      NUMBER        DEFAULT 1 NOT NULL,
    SUBTOTAL      NUMBER(12,2)  DEFAULT 0 NOT NULL
);
CREATE INDEX IDX_SHOP_ORDER_ITEM_ORDER ON SHOP_ORDER_ITEM(ORDER_ID);
COMMENT ON TABLE  SHOP_ORDER_ITEM IS '电商订单明细表';

