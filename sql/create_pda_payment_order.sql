-- ============================================
-- 支付宝支付订单表
-- ============================================
CREATE TABLE PDA_PAYMENT_ORDER (
    ID              VARCHAR2(64)    PRIMARY KEY,
    OUT_TRADE_NO    VARCHAR2(64)    NOT NULL,
    TRADE_NO        VARCHAR2(128),
    SUBJECT         VARCHAR2(256),
    TOTAL_AMOUNT    NUMBER(12,2)    NOT NULL,
    ORDER_STATUS    VARCHAR2(32)    DEFAULT 'WAIT_PAY' NOT NULL,
    BUYER_LOGON_ID  VARCHAR2(128),
    BUYER_ID        VARCHAR2(64),
    PAY_TIME        TIMESTAMP,
    NOTIFY_TIME     TIMESTAMP,
    CREATE_BY       VARCHAR2(64),
    CREATE_TIME     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_BY       VARCHAR2(64),
    UPDATE_TIME     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    REMARK          VARCHAR2(512)
);

-- 商户订单号唯一索引
CREATE UNIQUE INDEX IDX_PAYMENT_OUT_TRADE_NO ON PDA_PAYMENT_ORDER(OUT_TRADE_NO);

-- 交易号索引 (用于退款查询)
CREATE INDEX IDX_PAYMENT_TRADE_NO ON PDA_PAYMENT_ORDER(TRADE_NO);

-- 订单状态索引
CREATE INDEX IDX_PAYMENT_STATUS ON PDA_PAYMENT_ORDER(ORDER_STATUS);

-- 创建时间索引
CREATE INDEX IDX_PAYMENT_CREATE_TIME ON PDA_PAYMENT_ORDER(CREATE_TIME);

COMMENT ON TABLE PDA_PAYMENT_ORDER IS '支付宝支付订单表';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.ID IS '主键ID';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.OUT_TRADE_NO IS '商户订单号(业务系统生成,唯一)';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.TRADE_NO IS '支付宝交易号';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.SUBJECT IS '订单标题/描述';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.TOTAL_AMOUNT IS '支付金额(单位:元)';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.ORDER_STATUS IS '订单状态: WAIT_PAY-待支付, PAID-已支付, CLOSED-已关闭, REFUNDED-已退款';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.BUYER_LOGON_ID IS '买家支付宝账号';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.BUYER_ID IS '买家支付宝用户ID';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.PAY_TIME IS '支付时间';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.NOTIFY_TIME IS '通知时间';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.CREATE_BY IS '创建人';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.UPDATE_BY IS '更新人';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN PDA_PAYMENT_ORDER.REMARK IS '备注';
