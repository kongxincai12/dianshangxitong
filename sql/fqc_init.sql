-- 1. 扩展 DEFECTCODE 表，新增 FQC 标识列
-- ============================================================
ALTER TABLE DEFECTCODE ADD IS_FQC NUMBER(1) DEFAULT 0;
COMMENT ON COLUMN DEFECTCODE.IS_FQC IS '是否FQC缺陷项，1=是，0=否';
ALTER TABLE DEFECTCODE ADD FQC_DISPLAY_ORDER NUMBER(5) DEFAULT 9999;
COMMENT ON COLUMN DEFECTCODE.FQC_DISPLAY_ORDER IS 'FQC缺陷显示排序，数值越小越靠前';

-- 2. 新建 FQC_RECORDS 主记录表
-- ============================================================
CREATE TABLE FQC_RECORDS (
    ID               VARCHAR2(64)  NOT NULL,
    LOT_CODE         VARCHAR2(64)  NOT NULL,
    PRODUCT_TYPE     VARCHAR2(10)  NOT NULL,
    MODEL_NAME       VARCHAR2(128),
    TOTAL_QTY        NUMBER(10),
    GOOD_QTY         NUMBER(10),
    DEFECT_QTY       NUMBER(10),
    PASS_RATE        NUMBER(5,2),
    CYCLE_TIME       NUMBER(10,2),
    FORK_QTY         NUMBER(10),
    PACKAGE_QTY      NUMBER(10),
    INSPECTOR_ID     VARCHAR2(32)  NOT NULL,
    INSPECTOR_NAME   VARCHAR2(64),
    STATUS           VARCHAR2(20)  DEFAULT 'DRAFT',
    INSP_DATE        DATE,
    REOPEN_COUNT     NUMBER(3)     DEFAULT 0,
    LAST_REOPEN_TIME DATE,
    REMARK           VARCHAR2(512),
    CREATE_TIME      DATE,
    UPDATE_TIME      DATE,
    CONSTRAINT PK_FQC_RECORDS PRIMARY KEY (ID)
);

CREATE INDEX IDX_FQC_RECORDS_LOT ON FQC_RECORDS (LOT_CODE, INSP_DATE);
CREATE INDEX IDX_FQC_RECORDS_INSPECTOR ON FQC_RECORDS (INSPECTOR_ID, INSP_DATE);

COMMENT ON TABLE FQC_RECORDS IS 'FQC检验主记录表';
COMMENT ON COLUMN FQC_RECORDS.ID IS '主键UUID';
COMMENT ON COLUMN FQC_RECORDS.LOT_CODE IS '批次号';
COMMENT ON COLUMN FQC_RECORDS.PRODUCT_TYPE IS '产品类型：PNL=连片，PCS=单PCS';
COMMENT ON COLUMN FQC_RECORDS.MODEL_NAME IS '型号（从批次信息冗余存储）';
COMMENT ON COLUMN FQC_RECORDS.TOTAL_QTY IS '检验总数（用户输入）';
COMMENT ON COLUMN FQC_RECORDS.GOOD_QTY IS '良品数（用户输入）';
COMMENT ON COLUMN FQC_RECORDS.DEFECT_QTY IS '不良数量（后端聚合缺陷明细SUM）';
COMMENT ON COLUMN FQC_RECORDS.PASS_RATE IS '合格率% = GOOD_QTY/TOTAL_QTY*100';
COMMENT ON COLUMN FQC_RECORDS.CYCLE_TIME IS '周期';
COMMENT ON COLUMN FQC_RECORDS.FORK_QTY IS '叉数（PNL专用，PCS时为NULL）';
COMMENT ON COLUMN FQC_RECORDS.PACKAGE_QTY IS '包装数（PCS专用，PNL时为NULL）';
COMMENT ON COLUMN FQC_RECORDS.INSPECTOR_ID IS '检验员工号';
COMMENT ON COLUMN FQC_RECORDS.INSPECTOR_NAME IS '检验员姓名（冗余）';
COMMENT ON COLUMN FQC_RECORDS.STATUS IS '状态：DRAFT=草稿，SUBMITTED=已提交';
COMMENT ON COLUMN FQC_RECORDS.INSP_DATE IS '检验日期';
COMMENT ON COLUMN FQC_RECORDS.REOPEN_COUNT IS '撤回编辑次数，用于审计追踪';
COMMENT ON COLUMN FQC_RECORDS.LAST_REOPEN_TIME IS '最后撤回时间';
COMMENT ON COLUMN FQC_RECORDS.REMARK IS '备注';

-- 3. 新建 FQC_RECORD_DEFECTS 缺陷明细表
-- ============================================================
CREATE TABLE FQC_RECORD_DEFECTS (
    ID              VARCHAR2(64)  NOT NULL,
    RECORD_ID       VARCHAR2(64)  NOT NULL,
    DEFECT_CODE_ID  VARCHAR2(64),
    DEFECT_NAME     VARCHAR2(128) NOT NULL,
    DEFECT_QTY      NUMBER(10)    DEFAULT 0,
    IS_CUSTOM       NUMBER(1)     DEFAULT 0,
    DISPLAY_ORDER   NUMBER(5),
    CREATE_TIME     DATE,
    UPDATE_TIME     DATE,
    CONSTRAINT PK_FQC_RECORD_DEFECTS PRIMARY KEY (ID),
    CONSTRAINT FK_FQC_DEFECTS_RECORD FOREIGN KEY (RECORD_ID) REFERENCES FQC_RECORDS(ID)
);

CREATE INDEX IDX_FQC_DEFECTS_RECORD ON FQC_RECORD_DEFECTS (RECORD_ID);

COMMENT ON TABLE FQC_RECORD_DEFECTS IS 'FQC检验缺陷明细表';
COMMENT ON COLUMN FQC_RECORD_DEFECTS.ID IS '主键UUID';
COMMENT ON COLUMN FQC_RECORD_DEFECTS.RECORD_ID IS '关联FQC_RECORDS.ID';
COMMENT ON COLUMN FQC_RECORD_DEFECTS.DEFECT_CODE_ID IS '关联DEFECTCODE表主键（自定义缺陷时为NULL）';
COMMENT ON COLUMN FQC_RECORD_DEFECTS.DEFECT_NAME IS '缺陷名称';
COMMENT ON COLUMN FQC_RECORD_DEFECTS.DEFECT_QTY IS '不良数量';
COMMENT ON COLUMN FQC_RECORD_DEFECTS.IS_CUSTOM IS '0=预设缺陷项，1=用户自定义添加';
COMMENT ON COLUMN FQC_RECORD_DEFECTS.DISPLAY_ORDER IS '显示排序';

-- 4. 权限数据：插入 FQC 检验员角色
-- ============================================================
INSERT INTO MES_INSP_ROLES (ID, ROLE_CODE, ROLE_NAME, ROLE_LEVEL)
VALUES (SYS_GUID(), 'FQC_INSPECTOR', 'FQC检验员', 1);

COMMIT;
