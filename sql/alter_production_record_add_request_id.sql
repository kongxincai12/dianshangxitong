-- 设备作业提交幂等：先执行本脚本，再发布引用 REQUEST_ID 的后端版本。
-- 旧数据 REQUEST_ID 为 NULL，不受唯一索引影响。

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'MES_PRODUCTION_RECORD'
       AND COLUMN_NAME = 'REQUEST_ID';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE MES_PRODUCTION_RECORD ADD REQUEST_ID VARCHAR2(64)';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_INDEXES
     WHERE INDEX_NAME = 'UQ_MES_PROD_REQ_LOT';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE UNIQUE INDEX UQ_MES_PROD_REQ_LOT ON MES_PRODUCTION_RECORD (REQUEST_ID, LOT_CODE)';
    END IF;
END;
/

COMMENT ON COLUMN MES_PRODUCTION_RECORD.REQUEST_ID IS
    '客户端一次逻辑提交的幂等请求号；批量提交的多条记录共用同一请求号';

SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'MES_PRODUCTION_RECORD'
   AND COLUMN_NAME = 'REQUEST_ID';

SELECT INDEX_NAME, UNIQUENESS, STATUS
  FROM USER_INDEXES
 WHERE INDEX_NAME = 'UQ_MES_PROD_REQ_LOT';

