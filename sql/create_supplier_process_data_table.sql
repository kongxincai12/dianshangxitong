-- =====================================================
-- 供应商制程数据表 SQL 脚本
-- 数据库: Oracle
-- 用途: 存储从 Excel 上传的供应商制程数据
-- =====================================================

-- 1. 创建序列（用于主键自增）
CREATE SEQUENCE SEQ_SUPPLIER_PROCESS_DATA_ID
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- 2. 创建表
CREATE TABLE SUPPLIER_PROCESS_DATA (
    ID NUMBER(19) PRIMARY KEY,                          -- 主键ID
    BATCH_ID VARCHAR2(100),                             -- 批次号
    STATUS NUMBER(1) DEFAULT 0 NOT NULL,                -- 状态: 0=待发送, 1=发送成功, 2=发送失败
    ERROR_MSG VARCHAR2(500),                            -- 错误信息
    SUPPLIER_CODE VARCHAR2(100),                        -- 供应商编码
    TYPE VARCHAR2(100),                                 -- 检测类型
    MATERIAL_CATEGORY VARCHAR2(100),                    -- 物料大类
    MATERIAL_CLASSIFICATION VARCHAR2(100),              -- 物料细分类
    MATERIAL_CODE VARCHAR2(100),                        -- 物料代码
    STATION VARCHAR2(100),                              -- 工序
    SN VARCHAR2(200),                                   -- 条码SN
    SHIFT VARCHAR2(50) DEFAULT '0',                     -- 班别（默认0-白班）
    MACHINE_NO VARCHAR2(50) DEFAULT 'NA' NOT NULL,      -- 机台编号（默认NA）
    TEST_ITEM VARCHAR2(200),                            -- 测试项
    TEST_VALUE NUMBER(20, 6),                           -- 实际测试值
    TRANSIT_TIME DATE,                                  -- 测试过站时间
    RESULT VARCHAR2(50),                                -- 结果
    TOTAL_RESULT VARCHAR2(50),                          -- 总结果
    UPPER_LIMIT VARCHAR2(20),                           -- 测试上限
    LOWER_LIMIT VARCHAR2(20),                           -- 测试下限
    GUID VARCHAR2(32),                                  -- 唯一标识(32位)
    SUP_CREATE_TIME DATE NOT NULL,                      -- 供应商创建时间
    SUP_UPDATE_TIME DATE NOT NULL,                      -- 供应商更新时间
    CREATE_TIME DATE DEFAULT SYSDATE                    -- 创建时间
);

-- 3. 创建索引（提高查询性能）
CREATE INDEX IDX_SPD_BATCH_ID ON SUPPLIER_PROCESS_DATA(BATCH_ID);
CREATE INDEX IDX_SPD_STATUS ON SUPPLIER_PROCESS_DATA(STATUS);
CREATE INDEX IDX_SPD_GUID ON SUPPLIER_PROCESS_DATA(GUID);
CREATE INDEX IDX_SPD_SUPPLIER_CODE ON SUPPLIER_PROCESS_DATA(SUPPLIER_CODE);
CREATE INDEX IDX_SPD_SN ON SUPPLIER_PROCESS_DATA(SN);
CREATE INDEX IDX_SPD_SHIFT ON SUPPLIER_PROCESS_DATA(SHIFT);
CREATE INDEX IDX_SPD_MACHINE_NO ON SUPPLIER_PROCESS_DATA(MACHINE_NO);
CREATE INDEX IDX_SPD_BATCH_STATUS ON SUPPLIER_PROCESS_DATA(BATCH_ID, STATUS);

-- 4. 添加注释
COMMENT ON TABLE SUPPLIER_PROCESS_DATA IS '供应商制程数据表';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.ID IS '主键ID';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.BATCH_ID IS '批次号，用于标记同一批上传的文件';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.STATUS IS '状态: 0=待发送, 1=发送成功, 2=发送失败';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.ERROR_MSG IS '错误信息';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.SUPPLIER_CODE IS '供应商编码';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.TYPE IS '检测类型';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.MATERIAL_CATEGORY IS '物料大类';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.MATERIAL_CLASSIFICATION IS '物料细分类';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.MATERIAL_CODE IS '物料代码';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.STATION IS '工序';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.SN IS '条码SN';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.SHIFT IS '班别（0-白班/1-晚班）';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.MACHINE_NO IS '机台编号';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.TEST_ITEM IS '测试项';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.TEST_VALUE IS '实际测试值';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.TRANSIT_TIME IS '测试过站时间';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.RESULT IS '结果';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.TOTAL_RESULT IS '总结果';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.UPPER_LIMIT IS '测试上限';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.LOWER_LIMIT IS '测试下限';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.GUID IS '唯一标识(32位)';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.SUP_CREATE_TIME IS '供应商创建时间';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.SUP_UPDATE_TIME IS '供应商更新时间';
COMMENT ON COLUMN SUPPLIER_PROCESS_DATA.CREATE_TIME IS '创建时间';

