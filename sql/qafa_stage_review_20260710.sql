-- QA first-article staged review support.
-- Run before deploying backend code that writes stage fields.

ALTER TABLE QA_FA_TEMPLATE_SECTION ADD (
  STAGE_CODE      VARCHAR2(50),
  STAGE_NAME      VARCHAR2(100),
  STAGE_SORT_NO   NUMBER(10),
  STAGE_ENABLED   NUMBER(1) DEFAULT 0,
  FINAL_REQUIRED  NUMBER(1) DEFAULT 0,
  RELEASE_ON_PASS NUMBER(1) DEFAULT 0
);

UPDATE QA_FA_TEMPLATE_SECTION
   SET STAGE_CODE = NVL(STAGE_CODE, CODE),
       STAGE_NAME = NVL(STAGE_NAME, NAME),
       STAGE_SORT_NO = NVL(STAGE_SORT_NO, SORT_NO),
       STAGE_ENABLED = NVL(STAGE_ENABLED, 0),
       FINAL_REQUIRED = NVL(FINAL_REQUIRED, 0),
       RELEASE_ON_PASS = NVL(RELEASE_ON_PASS, 0)
 WHERE STAGE_CODE IS NULL
    OR STAGE_NAME IS NULL
    OR STAGE_SORT_NO IS NULL
    OR STAGE_ENABLED IS NULL
    OR FINAL_REQUIRED IS NULL
    OR RELEASE_ON_PASS IS NULL;

COMMENT ON COLUMN QA_FA_TEMPLATE_SECTION.STAGE_CODE IS '审核阶段编码';
COMMENT ON COLUMN QA_FA_TEMPLATE_SECTION.STAGE_NAME IS '审核阶段名称';
COMMENT ON COLUMN QA_FA_TEMPLATE_SECTION.STAGE_SORT_NO IS '审核阶段排序';
COMMENT ON COLUMN QA_FA_TEMPLATE_SECTION.STAGE_ENABLED IS '阶段是否启用:1启用,0不适用';
COMMENT ON COLUMN QA_FA_TEMPLATE_SECTION.FINAL_REQUIRED IS '是否参与最终判定:1是,0否';
COMMENT ON COLUMN QA_FA_TEMPLATE_SECTION.RELEASE_ON_PASS IS '阶段通过后是否允许生产放行:1是,0否';

CREATE TABLE QA_FA_STAGE_RESULT (
  ID              VARCHAR2(32)  NOT NULL,
  RECORD_ID       VARCHAR2(32)  NOT NULL,
  STAGE_CODE      VARCHAR2(50)  NOT NULL,
  STAGE_NAME      VARCHAR2(100) NOT NULL,
  SORT_NO         NUMBER(10),
  STATUS          VARCHAR2(20)  DEFAULT 'PENDING' NOT NULL,
  FINAL_REQUIRED  NUMBER(1)     DEFAULT 1,
  RELEASE_ON_PASS NUMBER(1)     DEFAULT 0,
  JUDGE_USER_ID   VARCHAR2(50),
  JUDGE_USER_NAME VARCHAR2(100),
  JUDGE_TIME      DATE,
  COMMENT_TEXT    VARCHAR2(1000),
  CREATE_TIME     DATE,
  UPDATE_TIME     DATE,
  CONSTRAINT PK_QA_FA_STAGE_RESULT PRIMARY KEY (ID)
);

CREATE INDEX IDX_QA_FA_STAGE_RESULT_RID ON QA_FA_STAGE_RESULT (RECORD_ID, SORT_NO);
CREATE UNIQUE INDEX UK_QA_FA_STAGE_RESULT_STAGE ON QA_FA_STAGE_RESULT (RECORD_ID, STAGE_CODE);

COMMENT ON TABLE QA_FA_STAGE_RESULT IS '首件记录阶段判定结果';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.RECORD_ID IS '首件记录ID';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.STAGE_CODE IS '阶段编码';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.STAGE_NAME IS '阶段名称';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.SORT_NO IS '阶段排序';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.STATUS IS 'PENDING/PASS/FAIL/NA';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.FINAL_REQUIRED IS '是否参与最终判定';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.RELEASE_ON_PASS IS '通过后是否生产放行';
COMMENT ON COLUMN QA_FA_STAGE_RESULT.COMMENT_TEXT IS '阶段判定备注';
